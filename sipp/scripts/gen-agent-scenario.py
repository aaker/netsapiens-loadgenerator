#!/usr/bin/env python3
#
# gen-agent-scenario.py - generate scripted agent (UAS, -oocsf) scenarios
# for the manual_test.sh call flows from the "agents" block of a flow spec
# in audio/flows/*.json.
#
# Each agent is a list of steps, played in order after answering the call:
#   ["talk", "<pcap name>", seconds]   play the pcap; move on after `seconds`
#   ["hold", min, max]                 re-INVITE a=sendonly, wait a random
#                                      min-max seconds, re-INVITE a=sendrecv
# and ends with one of:
#   ["end"]                            wait for the caller's BYE (hang up
#                                      ourselves 20s later)
#   ["transfer"]                       blind-REFER the caller to
#                                      __NEXT_EXT__@__AGENT_DOMAIN__, then
#                                      answer the 202/NOTIFY and the core's BYE
#
#   "agents": {
#     "sipp_uas_hold.xml": {
#       "title": "Hold call - the agent",
#       "steps": [["talk", "g711a-hold-term1", 32], ["hold", 20, 30], ..., ["end"]]
#     }
#   }
#
# Steps end on absolute deadlines (gettimeofday + variable arithmetic, polled
# in 500ms recv slices), so a re-INVITE or BYE from the core can arrive at any
# time without resetting a timer. The agent's own extension comes from the
# INVITE's request URI. A "transfer" agent needs manual_test.sh's per-device
# copy, which fills in __NEXT_EXT__ and __AGENT_DOMAIN__.
#
# Usage (from sipp/scripts):
#   ./gen-agent-scenario.py audio/flows/hold.json
#
# Keep a caller section (sipp_uac_flow.xml) that starts at a hold at least
# max hold + 4s long: the caller moves to the next section on the hold
# re-INVITE and restarts it on the resume only while the resume arrives more
# than 3s before that section's end.

import json
import os
import sys

SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))

NOW = '''      <gettimeofday assign_to="t_s,t_us"/>
      <assign assign_to="now" value="0"/>
      <add assign_to="now" variable="t_s"/>
      <assign assign_to="t_frac" value="0"/>
      <add assign_to="t_frac" variable="t_us"/>
      <divide assign_to="t_frac" value="1000000"/>
      <add assign_to="now" variable="t_frac"/>
'''

CONTACT = 'Contact: <sip:[$me]@[local_ip]:[local_port];transport=[transport]>'
UA = 'User-Agent: netsapiens-loadgenerator ([ua_version])'


def sdp(ver, direction):
    return f'''      v=0
      o=user1 53655765 {ver} IN IP[local_ip_type] [local_ip]
      s=-
      c=IN IP[media_ip_type] [media_ip]
      t=0 0
      m=audio [media_port] RTP/AVP 8 101
      a=rtpmap:8 PCMA/8000
      a=rtpmap:101 telephone-event/8000
      a=fmtp:101 0-15
      a={direction}
'''


def reply(code_text, extra='', body=None):
    """A response to the last request, optionally with SDP."""
    head = f'''      SIP/2.0 {code_text}
      [last_Via:]
      [last_From:]
      [last_To:]{extra}
      [last_Call-ID:]
      [last_CSeq:]
      {CONTACT}
      {UA}
'''
    if body is None:
        return head + '      Content-Length: 0\n'
    return head + '      Content-Type: application/sdp\n      Content-Length: [len]\n\n' + body


def send(msg, attrs=''):
    return f'''  <send{attrs}>
    <![CDATA[

{msg}
    ]]>
  </send>
'''


def request(method, cseq, extra='', body=None):
    head = f'''      {method} [$remote_contact] SIP/2.0
      Via: SIP/2.0/[transport] [local_ip]:[local_port];branch=[branch]
      From: [$local_to];tag=[pid]SIPpTag01[call_number]
      To: [$remote_from]
      Call-ID: [call_id]
      CSeq: {cseq} {method}
      {CONTACT}
{extra}      {UA}
      Max-Forwards: 70
'''
    if body is None:
        return head + '      Content-Length: 0\n'
    return head + '      Content-Type: application/sdp\n      Content-Length: [len]\n\n' + body


def generate(name, agent):
    steps = agent['steps']
    final = steps[-1][0]
    if final not in ('end', 'transfer'):
        sys.exit(f'{name}: the last step must be "end" or "transfer"')
    timed = steps[:-1]
    for s in timed:
        if s[0] not in ('talk', 'hold'):
            sys.exit(f'{name}: unknown step {s}')

    out = []
    w = out.append
    lines = [f'<!--   {i + 1}. ' + (f'talk {s[2]}s ({s[1]}.pcap)' if s[0] == 'talk'
                                    else f'hold {s[1]}-{s[2]}s (re-INVITE a=sendonly, then a=sendrecv)')
             for i, s in enumerate(timed)]
    lines.append(f'<!--   {len(timed) + 1}. ' + ('wait for the caller to hang up' if final == 'end'
                                                 else 'blind-REFER the caller to __NEXT_EXT__@__AGENT_DOMAIN__'))
    w(f'''<?xml version="1.0" encoding="ISO-8859-1" ?>
<!DOCTYPE scenario SYSTEM "sipp.dtd">

<!-- ====================================================================== -->
<!-- {agent['title']} (UAS, -oocsf).
<!-- Generated by gen-agent-scenario.py from {agent['spec']}.
<!-- Edit the spec and regenerate rather than editing this file.
<!--
<!-- After answering:
''' + '\n'.join(l for l in lines) + '''
<!-- Steps end on absolute deadlines, polled in 500ms recv slices, so a
<!-- re-INVITE or BYE from the core can arrive at any time.
<!-- ====================================================================== -->

<scenario name="''' + agent['title'] + '''">

  <recv request="INVITE" crlf="true" rrs="true">
    <action>
      <ereg regexp="[: ]*(.*)" search_in="hdr" header="From" assign_to="remote_from,remote_from"/>
      <ereg regexp="[: ]*([^;]*)" search_in="hdr" header="To" assign_to="local_to,local_to"/>
      <ereg regexp="sip:[^>]*" search_in="hdr" header="Contact" assign_to="remote_contact"/>
      <ereg regexp="INVITE sip:([^@;> ]+)@" search_in="msg" assign_to="me,me" checkIt="false"/>
      <log message="AGENT [$me]: answering callid=[call_id]"/>
    </action>
  </recv>

''')
    tag = ';tag=[pid]SIPpTag01[call_number]'
    w(send(reply('100 Trying', tag)))
    w(send(reply('180 Ringing', tag)))
    w('\n  <pause distribution="uniform" min="1000" max="2000"/>\n\n')
    w(send(reply('200 OK', tag, sdp(2353687637, 'sendrecv')), ' retrans="500"'))
    w('''
  <recv request="ACK" crlf="true">
  </recv>

''')

    cseq = 2
    ver = 2353687638
    # Phase i (1-based) is step i; a hold's phase is the time on hold.
    for i, s in enumerate(timed, 1):
        nxt = f'step{i + 1}'
        if s[0] == 'talk':
            w(f'''  <label id="step{i}"/>
  <nop next="poll">
    <action>
{NOW}      <assign assign_to="phase" value="{i}"/>
      <assign assign_to="deadline" value="{s[2]}"/>
      <add assign_to="deadline" variable="now"/>
      <log message="__PCAP__ call=[call_number] tick=[clock_tick]ms play={s[1]}.pcap stage=step-{i}"/>
      <exec play_pcap_audio="{s[1]}.pcap"/>
    </action>
  </nop>

''')
        else:
            for label, direction, after in ((f'step{i}', 'sendonly', f'held{i}'),
                                            (f'resume{i}', 'sendrecv', nxt)):
                w(f'''  <label id="{label}"/>
  <nop>
    <action><log message="AGENT [$me]: {label} (re-INVITE a={direction}) callid=[call_id]"/></action>
  </nop>
''')
                w(send(request('INVITE', cseq, body=sdp(ver, direction)), ' retrans="500"'))
                w(f'''  <recv timeout="10000" ontimeout="{after}" response="100" optional="true">
  </recv>
  <recv response="200" timeout="10000" ontimeout="{after}">
  </recv>
''')
                w(send(request('ACK', cseq), f' next="{after}"'))
                w('\n')
                if direction == 'sendonly':
                    w(f'''  <label id="held{i}"/>
  <nop next="poll">
    <action>
{NOW}      <sample assign_to="hold_len" distribution="uniform" min="{s[1]}" max="{s[2]}"/>
      <log message="AGENT [$me]: holding for [$hold_len]s"/>
      <assign assign_to="phase" value="{i}"/>
      <assign assign_to="deadline" value="0"/>
      <add assign_to="deadline" variable="hold_len"/>
      <add assign_to="deadline" variable="now"/>
    </action>
  </nop>

''')
                cseq += 1
                ver += 1

    # Poll until the phase's deadline, then go where that step leads.
    w('''  <!-- Wait for the current step's deadline. -->
  <label id="poll"/>
  <recv timeout="500" ontimeout="tick" request="INVITE" optional="true" next="core_reinvite">
  </recv>
  <recv request="BYE" timeout="500" ontimeout="tick" next="bye_200">
  </recv>

  <label id="tick"/>
  <nop>
    <action>
''' + NOW + '''      <assign assign_to="over" value="0"/>
      <add assign_to="over" variable="now"/>
      <subtract assign_to="over" variable="deadline"/>
      <test assign_to="phase_done" variable="over" compare="greater_than_equal" value="0"/>
''' + ''.join(f'      <test assign_to="in_{i}" variable="phase" compare="equal" value="{i}"/>\n'
              for i in range(1, len(timed) + 1)) + '''    </action>
  </nop>
  <nop test="phase_done" next="phase_end"/>
  <nop next="poll"/>
  <label id="phase_end"/>
''' + ''.join(f'  <nop test="in_{i}" next="{"resume%d" % i if s[0] == "hold" else "step%d" % (i + 1)}"/>\n'
              for i, s in enumerate(timed, 1)) + f'''  <nop next="step{len(timed) + 1}"/>

  <!-- A re-INVITE from the core (media re-point): answer, keep the step. -->
  <label id="core_reinvite"/>
''')
    w(send(reply('200 OK', body=sdp(ver, 'sendrecv')), ' retrans="500"'))
    w('''  <recv request="ACK" crlf="true" next="poll">
  </recv>

''')

    last = len(timed) + 1
    if final == 'end':
        w(f'''  <!-- Done talking: the caller hangs up; if not, hang up 20s later. -->
  <label id="step{last}"/>
  <recv timeout="20000" ontimeout="send_bye" request="INVITE" optional="true" next="core_reinvite_end">
  </recv>
  <recv request="BYE" timeout="20000" ontimeout="send_bye" next="bye_200">
  </recv>
  <label id="core_reinvite_end"/>
''')
        w(send(reply('200 OK', body=sdp(ver, 'sendrecv')), ' retrans="500"'))
        w(f'''  <recv request="ACK" crlf="true" next="step{last}">
  </recv>

''')
    else:
        w(f'''  <!-- Blind transfer to the next agent. -->
  <label id="step{last}"/>
  <nop>
    <action><log message="AGENT [$me]: REFER caller to __NEXT_EXT__@__AGENT_DOMAIN__ callid=[call_id]"/></action>
  </nop>
''')
        w(send(request('REFER', cseq, extra='      Refer-To: <sip:__NEXT_EXT__@__AGENT_DOMAIN__>\n'
                                             '      Referred-By: <sip:[$me]@__AGENT_DOMAIN__>\n'), ' retrans="500"'))
        cseq += 1
        w('''
  <!-- After the REFER: answer the transfer NOTIFYs and the core's BYE. -->
  <label id="post"/>
  <recv timeout="15000" ontimeout="send_bye" response="202" optional="true" next="post">
  </recv>
  <recv timeout="15000" ontimeout="send_bye" request="NOTIFY" optional="true" next="notify_200">
    <action>
      <ereg regexp="SIP/2.0 ([0-9]+)" search_in="body" assign_to="notify_status,notify_status" checkIt="false"/>
      <log message="AGENT [$me]: NOTIFY sipfrag [$notify_status]"/>
    </action>
  </recv>
  <recv request="BYE" timeout="15000" ontimeout="send_bye" next="bye_200">
  </recv>

  <label id="notify_200"/>
''')
        w(send(reply('200 OK'), ' next="post"'))
        w('\n')

    w('''  <label id="send_bye"/>
  <nop>
    <action><log message="AGENT [$me]: hanging up"/></action>
  </nop>
''')
    w(send(request('BYE', cseq), ' retrans="500"'))
    w('''  <recv response="200" timeout="5000" ontimeout="99" next="99">
  </recv>

  <label id="bye_200"/>
''')
    w(send(reply('200 OK'), ' next="99"'))
    w('''
  <label id="99"/>
  <timewait milliseconds="4000"/>

  <ResponseTimeRepartition value="10, 20, 30, 40, 50, 100, 150, 200"/>
  <CallLengthRepartition value="10, 50, 100, 500, 1000, 5000, 10000"/>

</scenario>
''')
    text = ''.join(out)
    # Close the header comment lines that were written without an ending.
    text = '\n'.join(l.ljust(73) + ' -->' if l.startswith('<!--') and not l.rstrip().endswith('-->') else l
                     for l in text.split('\n'))
    path = os.path.join(SCRIPTS_DIR, name)
    open(path, 'w').write(text)
    print(f'wrote {path}')


def main():
    if len(sys.argv) != 2:
        sys.exit(f'usage: {sys.argv[0]} audio/flows/<flow>.json')
    spec_path = sys.argv[1]
    spec = json.load(open(spec_path))
    for name, agent in spec.get('agents', {}).items():
        agent['spec'] = os.path.relpath(spec_path, SCRIPTS_DIR)
        generate(name, agent)


if __name__ == '__main__':
    main()
